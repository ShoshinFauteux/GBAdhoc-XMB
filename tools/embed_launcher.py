#!/usr/bin/env python3
"""embed_launcher.py PBP OUT.h -- the launcher EBOOT as a C array.

The desktop app and the command-line maker (tools/xw_cli.c) carry the
launcher inside them; this writes the header they include.  The PSP app has
its own copy of this step (psp/tools/embed_launcher.py, a committed header).
"""
import sys

src, out = sys.argv[1], sys.argv[2]
d = open(src, "rb").read()
with open(out, "w", newline="\n") as f:
    f.write("/* generated by tools/embed_launcher.py from launcher/EBOOT.PBP; do not edit */\n")
    f.write("static const unsigned char xw_launcher_pbp[] = {\n")
    for i in range(0, len(d), 16):
        f.write("  " + ",".join(str(b) for b in d[i:i + 16]) + ",\n")
    f.write("};\nstatic const size_t xw_launcher_pbp_len = %d;\n" % len(d))
