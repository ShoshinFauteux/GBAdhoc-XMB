"""Extract the few roots GBAdhoc XMB needs from Git for Windows' CA bundle into a C header.
usage: python tools/make_ca.py BUNDLE net_ca.h      (from psp/)
BUNDLE is any PEM CA bundle (Git for Windows ships one as ca-bundle.crt)."""
import re, subprocess, sys

BUNDLE = sys.argv[1]
WANT = [
    ("ISRG Root X1", "Let's Encrypt RSA root: raw.githubusercontent.com, objects.githubusercontent.com, thumbnails.libretro.com"),
    ("ISRG Root X2", "Let's Encrypt ECDSA root (LE's ECDSA chains)"),
    ("USERTrust ECC Certification Authority", "Sectigo ECC: github.com, api.github.com"),
    ("USERTrust RSA Certification Authority", "Sectigo RSA: github.com's RSA chain"),
    ("DigiCert Global Root G2", "spare: GitHub's former issuer"),
]
pems = re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", open(BUNDLE).read(), re.S)
found = {}
for p in pems:
    subj = subprocess.run(["openssl", "x509", "-noout", "-subject", "-enddate"], input=p, capture_output=True, text=True).stdout
    for cn, why in WANT:
        if re.search(r"CN\s*=\s*" + re.escape(cn) + r"\s*(,|$|\n)", subj) and cn not in found:
            found[cn] = (p, subj.strip().replace("\n", " | "), why)
missing = [cn for cn, _ in WANT if cn not in found]
if missing:
    sys.exit("missing: %s" % missing)
with open(sys.argv[2], "w", newline="\n") as f:
    f.write("/* net_ca.h -- generated by tools/make_ca.py from a PEM CA bundle\n"
            " * (Git for Windows' ca-bundle.crt).  The roots GBAdhoc XMB's hosts chain to (checked with openssl s_client,\n"
            " * 2026-11-05).  Do not edit; regenerate. */\n")
    f.write("static const char net_ca_pem[] =\n")
    for cn, _ in WANT:
        p, subj, why = found[cn]
        f.write("/* %s -- %s\n * %s */\n" % (cn, why, subj))
        for line in p.splitlines():
            f.write('"%s\\n"\n' % line)
    f.write(";\n")
print("wrote", sys.argv[2], [cn for cn, _ in WANT])
