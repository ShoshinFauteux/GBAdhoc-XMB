#!/usr/bin/env python3
"""gen/launcher_pbp.h from ../launcher/EBOOT.PBP (the per-game launcher every
entry carries; build it first: launcher/Makefile).  The same embedding as
tools/embed_launcher.py does for the desktop app.

    python tools/embed_launcher.py          (from psp/)
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, '..', 'launcher', 'EBOOT.PBP')
OUT = os.path.join(ROOT, 'gen', 'launcher_pbp.h')

d = open(SRC, 'rb').read()
with open(OUT, 'w', newline='\n') as f:
    f.write('/* generated by tools/embed_launcher.py from launcher/EBOOT.PBP; do not edit */\n')
    f.write('#ifndef XMB_LAUNCHER_PBP_H\n#define XMB_LAUNCHER_PBP_H\n#include <stddef.h>\n')
    f.write('static const unsigned char xw_launcher_pbp[] = {\n')
    for i in range(0, len(d), 24):
        f.write('  ' + ','.join(str(b) for b in d[i:i + 24]) + ',\n')
    f.write('};\nstatic const size_t xw_launcher_pbp_len = %d;\n#endif\n' % len(d))
print(len(d), 'bytes ->', OUT)
