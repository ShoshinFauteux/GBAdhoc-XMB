#!/usr/bin/env python3
"""Build gen/xmb_names.h: the titles GBAdhoc XMB recognises ROMs by.

    python tools/make_names.py <cache dir>        (from psp/)

Sources (fetched into <cache dir> once, then reused):
  http://thumbnails.libretro.com/Nintendo - Game Boy Advance/Named_Boxarts/  (Apache index)
  ...                Nintendo - Game Boy/Named_Boxarts/, Nintendo - Game Boy Color/Named_Boxarts/
  https://api.github.com/repos/ShoshinFauteux/GBAdhoc-heroart/git/trees/main?recursive=1

Named_Boxarts files are named by No-Intro title with the characters
&*/:`<>?\\|" replaced by '_' (libretro's rule), so each name is exactly the
URL the box art lives at -- matching a ROM to a name IS finding its art.  The
hero repo's masters/ adds the names hero art exists for (ROM hacks included).

The blob is "<sys>\\t<name>\\n" lines (sys: A=GBA, B=GB, C=GBC, H=hero),
sorted, zlib-compressed; the app inflates it once at start.  Only titles:
no ROM data, no art.
"""
import json, os, re, sys, urllib.parse, urllib.request, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), 'gen', 'xmb_names.h')
SYS = [('A', 'Nintendo - Game Boy Advance'), ('B', 'Nintendo - Game Boy'), ('C', 'Nintendo - Game Boy Color')]


def fetch(url, path):
    if not os.path.exists(path):
        req = urllib.request.Request(url, headers={'User-Agent': 'GBAdhoc-XMB-build/1.0'})
        with urllib.request.urlopen(req, timeout=60) as r, open(path, 'wb') as f:
            f.write(r.read())
    return open(path, 'rb').read().decode('utf-8', 'replace')


def main():
    cache = sys.argv[1]
    os.makedirs(cache, exist_ok=True)
    lines = set()
    for tag, name in SYS:
        html = fetch('http://thumbnails.libretro.com/' + urllib.parse.quote(name) + '/Named_Boxarts/',
                     os.path.join(cache, f'names_{tag}.html'))
        for h in re.findall(r'href="([^"?/]+)\.png"', html):
            lines.add(f'{tag}\t{urllib.parse.unquote(h)}')
    tree = json.loads(fetch('https://api.github.com/repos/ShoshinFauteux/GBAdhoc-heroart/git/trees/main?recursive=1',
                            os.path.join(cache, 'heroart_tree.json')))
    for t in tree.get('tree', []):
        m = re.match(r'masters/(.+)\.png$', t['path'])
        if m:
            lines.add(f'H\t{m.group(1)}')
    blob = ('\n'.join(sorted(lines)) + '\n').encode('utf-8')
    z = zlib.compress(blob, 9)
    with open(OUT, 'w') as f:
        f.write('/* generated by tools/make_names.py -- do not edit.  Titles only. */\n')
        f.write('#ifndef XMB_NAMES_H\n#define XMB_NAMES_H\n')
        f.write(f'#define XMB_NAMES_RAW {len(blob)}\n#define XMB_NAMES_COUNT {len(lines)}\n')
        f.write(f'static const unsigned char xmb_names_z[{len(z)}] = {{\n')
        for i in range(0, len(z), 24):
            f.write('  ' + ','.join(str(b) for b in z[i:i + 24]) + ',\n')
        f.write('};\n#endif\n')
    print(len(lines), 'names,', len(blob), 'bytes ->', len(z), 'compressed')


if __name__ == '__main__':
    main()
