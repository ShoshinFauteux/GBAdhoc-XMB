#!/usr/bin/env python3
"""embed.py UI_DIR OUT.c -- every file under UI_DIR as a C array, for host.c.

The app serves its own UI from inside the exe (https://xmb.gbadhoc/<path>),
so it is one file with nothing to unpack."""
import os
import sys

MIME = {
    ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8",
    ".js": "text/javascript; charset=utf-8", ".png": "image/png", ".svg": "image/svg+xml",
    ".woff2": "font/woff2", ".json": "application/json", ".txt": "text/plain; charset=utf-8",
}

ui, out = sys.argv[1], sys.argv[2]
files = []
for root, _, names in os.walk(ui):
    for n in sorted(names):
        p = os.path.join(root, n)
        rel = os.path.relpath(p, ui).replace(os.sep, "/")
        files.append((rel, p))
files.sort()
with open(out, "w") as f:
    f.write("/* generated by embed.py from desktop/ui; do not edit */\n")
    f.write("typedef struct { const char *path, *mime; const unsigned char *data; unsigned len; } ui_res;\n")
    for i, (rel, p) in enumerate(files):
        d = open(p, "rb").read()
        f.write("static const unsigned char r%d[] = {" % i)
        for k in range(0, len(d), 24):
            f.write("\n" + ",".join(str(b) for b in d[k:k + 24]) + ",")
        f.write("0};\n")
    f.write("const ui_res g_ui[] = {\n")
    for i, (rel, p) in enumerate(files):
        ext = os.path.splitext(rel)[1].lower()
        f.write('  { "%s", "%s", r%d, %d },\n' % (rel, MIME.get(ext, "application/octet-stream"), i,
                                                  os.path.getsize(p)))
    f.write("};\nconst int g_nui = %d;\n" % len(files))
print("embedded %d files" % len(files))
